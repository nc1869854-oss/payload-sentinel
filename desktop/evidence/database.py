def update_finding_state(finding_id: int, state: str,
                          analyst_note: str = "") -> None:
    """Update the lifecycle state of a finding."""
    import datetime
    now = datetime.datetime.now().isoformat(timespec="seconds")
    conn = get_connection()
    conn.execute(
        "UPDATE findings SET state=?, analyst_note=?, updated_at=? WHERE id=?",
        (state, analyst_note, now, finding_id)
    )
    conn.commit()
    conn.close()


def get_findings(session_id: str) -> list:
    """Return all findings for a session, ordered by severity."""
    conn = get_connection()
    severity_order = "CASE severity WHEN 'CRITICAL' THEN 0 WHEN 'HIGH' THEN 1 WHEN 'MEDIUM' THEN 2 WHEN 'LOW' THEN 3 ELSE 4 END"
    rows = conn.execute(
        f"SELECT * FROM findings WHERE session_id=? ORDER BY {severity_order}, created_at DESC",
        (session_id,)
    ).fetchall()
    conn.close()
    return [dict(r) for r in rows]


