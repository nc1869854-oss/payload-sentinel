# ─── Global search ────────────────────────────────────────────────────────────

def global_search(session_id: str, query: str, limit: int = 200) -> dict:
    """
    Search across packets, flows, findings, notes, and timeline events
    for a session. Returns a dict with results per category.

    Uses SQLite LIKE for broad matching — fast for typical analyst queries.
    """
    q = f"%{query}%"
    conn = get_connection()

    packets = conn.execute(
        """SELECT packet_number, capture_time, protocol, src_ip, dst_ip,
                  src_port, dst_port, risk_level
           FROM packets
           WHERE session_id=?
             AND (src_ip LIKE ? OR dst_ip LIKE ? OR protocol LIKE ?
                  OR CAST(src_port AS TEXT) LIKE ? OR CAST(dst_port AS TEXT) LIKE ?)
           ORDER BY packet_number ASC LIMIT ?""",
        (session_id, q, q, q, q, q, limit)
    ).fetchall()

    flows = conn.execute(
        """SELECT flow_id, protocol, src_ip, src_port, dst_ip, dst_port,
                  packet_count, byte_count, risk_level
           FROM flows
           WHERE session_id=?
             AND (src_ip LIKE ? OR dst_ip LIKE ? OR protocol LIKE ?
                  OR CAST(src_port AS TEXT) LIKE ? OR CAST(dst_port AS TEXT) LIKE ?)
           LIMIT ?""",
        (session_id, q, q, q, q, q, limit)
    ).fetchall()

    findings = conn.execute(
        """SELECT id, severity, title, description, state
           FROM findings
           WHERE session_id=?
             AND (title LIKE ? OR description LIKE ? OR evidence LIKE ?)
           LIMIT ?""",
        (session_id, q, q, q, limit)
    ).fetchall()

    notes = conn.execute(
        """SELECT id, created_at, target_type, target_id, content
           FROM notes
           WHERE session_id=? AND content LIKE ?
           LIMIT ?""",
        (session_id, q, limit)
    ).fetchall()

    timeline = conn.execute(
        """SELECT id, event_time, event_type, description
           FROM timeline_events
           WHERE session_id=? AND description LIKE ?
           LIMIT ?""",
        (session_id, q, limit)
    ).fetchall()

    conn.close()

    return {
        "query":    query,
        "packets":  [dict(r) for r in packets],
        "flows":    [dict(r) for r in flows],
        "findings": [dict(r) for r in findings],
        "notes":    [dict(r) for r in notes],
        "timeline": [dict(r) for r in timeline],
    }
