# ─── Statistics helper ────────────────────────────────────────────────────────

def get_session_statistics(session_id: str) -> dict:
    """
    Calculate aggregate statistics for a session.
    Returns a dict the UI and report builder can display directly.
    """
    conn = get_connection()

    # Basic totals
    totals = conn.execute(
        """
        SELECT
            COUNT(*)                          AS total_packets,
            COALESCE(SUM(packet_size), 0)     AS total_bytes,
            COALESCE(SUM(payload_size), 0)    AS total_payload_bytes
        FROM packets
        WHERE session_id = ?
        """,
        (session_id,)
    ).fetchone()

    # Protocol distribution
    proto_rows = conn.execute(
        """
        SELECT protocol, COUNT(*) AS count
        FROM packets
        WHERE session_id = ?
        GROUP BY protocol
        ORDER BY count DESC
        """,
        (session_id,)
    ).fetchall()

    # Top source IPs
    top_src = conn.execute(
        """
        SELECT src_ip, COUNT(*) AS count
        FROM packets
        WHERE session_id = ? AND src_ip IS NOT NULL
        GROUP BY src_ip
        ORDER BY count DESC
        LIMIT 10
        """,
        (session_id,)
    ).fetchall()

    # Top destination IPs
    top_dst = conn.execute(
        """
        SELECT dst_ip, COUNT(*) AS count
        FROM packets
        WHERE session_id = ? AND dst_ip IS NOT NULL
        GROUP BY dst_ip
        ORDER BY count DESC
        LIMIT 10
        """,
        (session_id,)
    ).fetchall()

    # Flow count
    flow_count = conn.execute(
        "SELECT COUNT(*) FROM flows WHERE session_id = ?", (session_id,)
    ).fetchone()[0]

    # Alert count
    alert_count = conn.execute(
        "SELECT COUNT(*) FROM alerts WHERE session_id = ?", (session_id,)
    ).fetchone()[0]

    conn.close()

    return {
        "total_packets":       totals["total_packets"],
        "total_bytes":         totals["total_bytes"],
        "total_payload_bytes": totals["total_payload_bytes"],
        "total_flows":         flow_count,
        "total_alerts":        alert_count,
        "protocol_distribution": [dict(r) for r in proto_rows],
        "top_sources":           [dict(r) for r in top_src],
        "top_destinations":      [dict(r) for r in top_dst],
    }


